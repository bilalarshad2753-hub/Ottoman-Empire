export const getEraLabel = (era: Sultan["era"]) => {
  switch (era) {
    case "rise": return "Rise (1299–1453)";
    case "golden": return "Golden Age (1453–1566)";
    case "stagnation": return "Stagnation (1566–1683)";
    case "decline": return "Decline & Reform (1683–1922)";
  }
};

export const getEraColor = (era: Sultan["era"]) => {
  switch (era) {
    case "rise": return "ottoman-green";
    case "golden": return "ottoman-gold";
    case "stagnation": return "ottoman-gold-dim";
    case "decline": return "ottoman-crimson";
  }
};

export const getSultanById = (id: number) => sultans.find(s => s.id === id);
